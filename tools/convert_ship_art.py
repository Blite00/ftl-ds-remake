#!/usr/bin/env python3
"""Convert the locally imported Kestrel hull to a DS RGB555 bitmap.

Requires Pillow; the archive importer itself has no external dependencies.
"""
import argparse
import io
import json
from pathlib import Path
from PIL import Image, ImageDraw
from import_ftl import PkgArchive, xml_root


def c_bitmap(name, source):
    pixels = [0 if a < 96 else 0x8000 | (r >> 3) | ((g >> 3) << 5) | ((b >> 3) << 10)
              for r, g, b, a in source.get_flattened_data()]
    result = ['#define %s_WIDTH %d' % (name.upper(), source.width),
              '#define %s_HEIGHT %d' % (name.upper(), source.height),
              'static const uint16_t %s[%d] = {' % (name, len(pixels))]
    result.extend('    ' + ','.join('0x%04x' % p for p in pixels[i:i+16]) + ','
                  for i in range(0, len(pixels), 16))
    return result + ['};']


def fit_canvas(image, size):
    image = image.copy()
    image.thumbnail(size, Image.Resampling.LANCZOS)
    canvas = Image.new('RGBA', size)
    canvas.alpha_composite(image, ((size[0]-image.width)//2, (size[1]-image.height)//2))
    return canvas


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument('--archive', type=Path)
    args = ap.parse_args()
    output = Path(__file__).resolve().parents[1] / 'generated'
    source = Image.open(output / 'original/img/ship/kestral_base.png').convert('RGBA')
    source.thumbnail((240, 90), Image.Resampling.LANCZOS)
    width, height = source.size
    pixels = [0 if a < 128 else 0x8000 | (r >> 3) | ((g >> 3) << 5) | ((b >> 3) << 10)
              for r, g, b, a in source.get_flattened_data()]
    header = ['/* Local original FTL art. Generated by tools/convert_ship_art.py. */',
              '#ifndef SHIP_ART_H', '#define SHIP_ART_H', '#include <stdint.h>',
              '#define KESTREL_ART_WIDTH %d' % width,
              '#define KESTREL_ART_HEIGHT %d' % height,
              'static const uint16_t kestrel_art[%d] = {' % len(pixels)]
    for i in range(0, len(pixels), 16):
        header.append('    ' + ','.join('0x%04x' % pixel for pixel in pixels[i:i+16]) + ',')
    header.extend(['};', '#endif', ''])
    (output / 'ship_art.h').write_text('\n'.join(header), encoding='utf-8')
    source.save(output / 'kestrel_ds.png')
    print('Converted Kestrel hull to %dx%d RGB555 (%d bytes)' % (width, height, len(pixels) * 2))

    archive_path = args.archive
    if archive_path is None:
        archive_path = Path(json.loads((output / 'manifest.json').read_text())['archive'])
    archive = PkgArchive(archive_path)

    def original(name):
        payload = archive.read(name)
        dest = output / 'original' / name
        dest.parent.mkdir(parents=True, exist_ok=True)
        dest.write_bytes(payload)
        return Image.open(io.BytesIO(payload)).convert('RGBA')

    hull = Image.open(output / 'original/img/ship/kestral_base.png').convert('RGBA')
    enemy = original('img/ships_glow/auto_basic_base.png')
    animations_data = archive.read('data/animations.xml')
    (output / 'original/data/animations.xml').write_bytes(animations_data)
    animations = xml_root(animations_data)
    crew_anim = animations.find(".//anim[@name='human_walk_down']/desc")
    sheet = animations.find(".//animSheet[@name='human']")
    fw, fh = int(sheet.get('fw')), int(sheet.get('fh'))
    cx, cy = int(crew_anim.get('x')) * fw, int(crew_anim.get('y')) * fh
    crew = original('img/' + sheet.text).crop((cx, cy, cx + fw, cy + fh))
    ship_xml = xml_root(archive.read('data/kestral.xml'))
    bounds = ship_xml.find('.//img')
    floor_offset = ship_xml.find('.//offsets/floor')
    hx, hy = int(bounds.get('x')), int(bounds.get('y'))
    fx, fy = int(floor_offset.get('x')), int(floor_offset.get('y'))
    floor = original('img/ship/kestral_floor.png')
    layered = hull.copy()
    layered.alpha_composite(floor, (fx, fy))
    tactical = Image.new('RGBA', (256, 88))
    # Original hull bounds start (-59,-103), original grid tiles are 35px.
    # 0.4 scale gives 14px tiles, grid origin (23,25) on the bottom screen.
    tactical.alpha_composite(layered.resize((261, 167), Image.Resampling.LANCZOS),
                             (round(23 + hx * 0.4), round(25 + hy * 0.4) - 23))
    assets = {'combat_kestrel': fit_canvas(hull, (110, 70)),
              'combat_enemy': fit_canvas(enemy, (90, 65)),
              'combat_crew': crew.resize((14, 14), Image.Resampling.NEAREST),
              'tactical_hull': tactical}
    for system in ('shields', 'weapons', 'engines', 'oxygen'):
        assets['icon_' + system] = fit_canvas(original('img/icons/s_%s.png' % system), (12, 12))
    combat = ['/* Converted original local FTL art. Do not redistribute. */',
              '#ifndef COMBAT_ART_H', '#define COMBAT_ART_H', '#include <stdint.h>',
              '#define TACTICAL_HULL_SCREEN_X 0', '#define TACTICAL_HULL_SCREEN_Y 23',
              '#define TACTICAL_GRID_X 23', '#define TACTICAL_GRID_Y 25',
              '#define TACTICAL_TILE_X 14', '#define TACTICAL_TILE_Y 14']
    total = 0
    for name, asset in assets.items():
        combat.extend(c_bitmap(name, asset))
        asset.save(output / (name + '.png'))
        total += asset.width * asset.height * 2
    combat.extend(['#endif', ''])
    (output / 'combat_art.h').write_text('\n'.join(combat), encoding='utf-8')
    print('Converted %d combat bitmaps, %d bytes of RGB555 data' % (len(assets), total))

    blueprint = xml_root(archive.read('data/blueprints.xml')).find(
        ".//shipBlueprint[@name='PLAYER_SHIP_HARD']")
    interior = ['/* Original Kestrel furnishings, from the local FTL archive. */',
                '#ifndef INTERIOR_ART_H', '#define INTERIOR_ART_H', '#include <stdint.h>']
    metadata = []
    interior_bytes = 0
    reference_image = layered.copy()
    room_data = json.loads((output / 'kestrel.json').read_text())
    for system in blueprint.find('systemList'):
        if system.get('start') != 'true':
            continue
        name = 'interior_' + system.tag
        reference = system.get('img')
        path = 'img/ship/interior/%s.png' % reference
        asset = original(path)
        original_size = asset.size
        room = next(r for r in room_data['rooms'] if r['id'] == int(system.get('room')))
        reference_image.alpha_composite(asset, (room['x'] * 35 - hx, room['y'] * 35 - hy))
        asset = asset.resize((round(asset.width * 0.4), round(asset.height * 0.4)), Image.Resampling.LANCZOS)
        interior.append('/* %s; Kestrel room %s */' % (path, system.get('room')))
        interior.append('#define %s_ROOM %s' % (name.upper(), system.get('room')))
        interior.extend(c_bitmap(name, asset))
        asset.save(output / (name + '.png'))
        metadata.append({'system': system.tag, 'room': int(system.get('room')),
                         'blueprint_img': reference, 'source': path,
                         'original_size': original_size, 'converted_size': asset.size,
                         'array': name})
        interior_bytes += asset.width * asset.height * 2
    interior.extend(['#endif', ''])
    (output / 'interior_art.h').write_text('\n'.join(interior), encoding='utf-8')
    (output / 'interior_art.json').write_text(json.dumps(metadata, indent=2), encoding='utf-8')
    print('Converted %d exact Kestrel room furnishings, %d bytes' % (len(metadata), interior_bytes))
    # Walls/door positions reconstructed from the original layout, not a game screenshot.
    draw = ImageDraw.Draw(reference_image)
    for room in room_data['rooms']:
        x, y = room['x'] * 35 - hx, room['y'] * 35 - hy
        draw.rectangle((x, y, x + room['w']*35, y + room['h']*35), outline=(40,40,36,255), width=2)
    for door in room_data['doors']:
        x, y = door['x'] * 35 - hx, door['y'] * 35 - hy
        if door['vertical']:
            draw.line((x,y+10,x,y+25), fill=(225,214,173,255), width=3)
        else:
            draw.line((x+10,y,x+25,y), fill=(225,214,173,255), width=3)
    labeled = Image.new('RGBA', (reference_image.width, reference_image.height+38), (12,19,26,255))
    labeled.alpha_composite(reference_image, (0,38))
    ImageDraw.Draw(labeled).text((12,8), 'KESTREL - RECONSTRUCTED FROM ORIGINAL ASSETS (not gameplay)', fill='white')
    labeled.save(output / 'kestrel_original_asset_reference.png')
    audit = {'reference': 'Asset reconstruction, not original gameplay screenshot',
             'hull_world_origin': [hx,hy], 'floor_offset_from_hull': [fx,fy],
             'floor_world_origin': [hx+fx,hy+fy], 'original_tile_px': 35, 'ds_tile_px': 14,
             'crew_animation': 'human_walk_down first frame (no idle animation declared)',
             'crew_source_rectangle': [cx,cy,cx+fw,cy+fh],
             'crew_previous_error': 'frame 0,0 is human_portrait in animations.xml',
             'crew_color_layers': 'Original base only; randomized clothing/hair tint layers not reconstructed',
             'furnishing_previous_error': '20px bounding thumbnail was too small for 28px double rooms',
             'floor_previous_error': 'Floor image was omitted; now composited at XML offset'}
    (output / 'art_audit.json').write_text(json.dumps(audit, indent=2), encoding='utf-8')


if __name__ == '__main__':
    main()
