#!/usr/bin/env python3
"""Import the 27 base-game ship achievements (3 per cruiser, original order).

Writes generated/achievement_catalog.h with each achievement's original name and
description. Lanius (Advanced Edition) achievements are excluded. The DS ids are
class*3+k in the hangar class order (Kestrel, Stealth, Mantis, Engi, Federation,
Slug, Rock, Zoltan, Crystal), matching source/achievements.h. Output stays local.
"""
import argparse
import hashlib
import json
import re
from pathlib import Path
from import_ftl import PkgArchive

ORDER = ['ACH_UNITED_FEDERATION', 'ACH_FULL_ARSENAL', 'ACH_TOUGH_SHIP',
         'ACH_STEALTH_DESTROY', 'ACH_STEALTH_AVOID', 'ACH_STEALTH_TACTICAL',
         'ACH_MANTIS_CREW_DEAD', 'ACH_MANTIS_SLAUGHTER', 'ACH_MANTIS_SURVIVOR',
         'ACH_ROBOTIC', 'ACH_ONLY_DRONES', 'ACH_IONED',
         'ACH_FED_PATIENCE', 'ACH_FED_DIPLOMACY', 'ACH_FED_UPGRADE',
         'ACH_SLUG_VISION', 'ACH_SLUG_NEBULA', 'ACH_SLUG_BIO',
         'ACH_ROCK_FIRE', 'ACH_ROCK_MISSILES', 'ACH_ROCK_CRYSTAL',
         'ACH_ENERGY_SHIELDS', 'ACH_ENERGY_POWER', 'ACH_ENERGY_MANPOWER',
         'ACH_CRYSTAL_SHARD', 'ACH_CRYSTAL_LOCKDOWN', 'ACH_CRYSTAL_CLASH']


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument('archive', type=Path, nargs='?')
    args = ap.parse_args()
    output = Path(__file__).resolve().parents[1] / 'generated'
    archive = PkgArchive(args.archive or Path(json.loads((output / 'manifest.json').read_text())['archive']))
    raw = archive.read('data/text_achievements.xml')
    text = dict(re.findall(r'<text name="([^"]*)"[^>]*>([^<]*)<', raw.decode('utf-8')))
    rows = []
    for ach in ORDER:
        name, desc = text.get(ach + '_name'), text.get(ach + '_desc')
        if not name or not desc:
            raise ValueError('Missing achievement text ' + ach)
        rows.append((ach, name.strip(), desc.strip()))
    header = ['/* Generated by tools/import_achievements.py from the owner\'s FTL archive. Do not redistribute. */',
              '#ifndef FTL_DS_ACHIEVEMENT_CATALOG_H', '#define FTL_DS_ACHIEVEMENT_CATALOG_H',
              '#define IMPORTED_ACHIEVEMENT_COUNT %d' % len(rows),
              'typedef struct { const char *id,*name,*desc; } ImportedAchievement;',
              'static const ImportedAchievement imported_achievements[IMPORTED_ACHIEVEMENT_COUNT] = {']
    header += ['    {%s,%s,%s},' % (json.dumps(a), json.dumps(n), json.dumps(d)) for a, n, d in rows]
    header += ['};', '#endif', '']
    (output / 'achievement_catalog.h').write_text('\n'.join(header), encoding='utf-8')
    (output / 'achievement_catalog.json').write_text(json.dumps({'source': 'data/text_achievements.xml', 'sha256': hashlib.sha256(raw).hexdigest(),
                                                                 'achievements': [dict(id=a, name=n, desc=d) for a, n, d in rows]}, indent=2), encoding='utf-8')
    print('Imported %d ship achievements' % len(rows))


if __name__ == '__main__':
    main()
